// Available identifiers for the admin icon picker.
export const CATEGORY_ICON_NAMES = Object.keys(ICON_BY_IDENTIFIER);

export const CATEGORY_ICON_MAP = { ...ICON_BY_IDENTIFIER, ...ICON_BY_EMOJI };

export function getCategoryIcon(icon) {
  if (typeof icon === 'function') return icon;
  if (typeof icon !== 'string') return null;
  return ICON_BY_IDENTIFIER[icon.toLowerCase()] || ICON_BY_EMOJI[icon] || null;
}

export default function CategoryIcon({ icon, size = 16, className = '', strokeWidth = 2, ...rest }) {
  const IconComponent = getCategoryIcon(icon);
  if (IconComponent) {
    return <IconComponent size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" {...rest} />;
  }
  if (typeof icon === 'string') {
    return <span className={className} aria-hidden="true">{icon}</span>;
  }
  return null;
}
