import api from './api';

export const userService = {
  updateMe: (data) => api.patch('/users/me', data),
  uploadAvatar: (formData) => api.post('/users/me/avatar', formData, { headers: { 'Content-Type': 'multipart/form-data' } }),
  getMyProfile: () => api.get('/users/me/profile'),
  updateProfile: (data) => api.patch('/users/me/profile', data),
  uploadResume: (formData) => api.post('/users/me/resume', formData, { headers: { 'Content-Type': 'multipart/form-data' } }),
  getFreelancerProfile: (userId) => api.get(`/users/${userId}/profile`),
  getProfileCard: (userId) => api.get(`/users/${userId}/profile-card`),
  getFullProfile: (userId) => api.get(`/users/${userId}/full-profile`),
  getClientProfile: (userId) => api.get(`/users/${userId}/client-profile`),
  searchFreelancers: (params) => api.get('/users/freelancers', { params }),
  addExperience: (data) => api.post('/users/me/experience', data),
  updateExperience: (id, data) => api.put(`/users/me/experience/${id}`, data),
  deleteExperience: (id) => api.delete(`/users/me/experience/${id}`),
  addEducation: (data) => api.post('/users/me/education', data),
  updateEducation: (id, data) => api.put(`/users/me/education/${id}`, data),
  deleteEducation: (id) => api.delete(`/users/me/education/${id}`),
  addCertification: (data) => api.post('/users/me/certifications', data),
  updateCertification: (id, data) => api.put(`/users/me/certifications/${id}`, data),
  deleteCertification: (id) => api.delete(`/users/me/certifications/${id}`),
  addPortfolioItem: (formData) => api.post('/users/me/portfolio', formData, { headers: { 'Content-Type': 'multipart/form-data' } }),
  updatePortfolioItem: (id, formData) => api.put(`/users/me/portfolio/${id}`, formData, { headers: { 'Content-Type': 'multipart/form-data' } }),
  deletePortfolioItem: (id) => api.delete(`/users/me/portfolio/${id}`),
  getSavedJobs: () => api.get('/users/me/saved-jobs'),
  toggleSaveJob: (jobId) => api.post(`/users/me/saved-jobs/${jobId}`),
  getSavedCatalogs: () => api.get('/users/me/saved-catalogs'),
  toggleSaveCatalog: (catalogId) => api.post(`/users/me/saved-catalogs/${catalogId}`),
};
